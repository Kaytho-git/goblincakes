#!/usr/bin/env python3
"""Draws the square GOBLINCAKES frames for the Plasma theme.

Plasma draws text fields, buttons, highlights and tooltips (also inside AppGrid and
every popup) from SVGs in the theme. Breeze's have rounded corners and glows; these
are flat, square and in the palette. Run from the repo root:

    python3 tools/plasma-frames.py
"""
from pathlib import Path

THEME = Path("files/system/usr/share/plasma/desktoptheme/goblincakes")

# Palette (see CLAUDE.md)
NIGHT = "#0E1420"
DEEP = "#12203A"
# The accent isn't written as a colour: Plasma paints it with the system's accent (the colour
# chosen in GOBLINCAKES Config → Utseende, Button DecorationFocus in kdeglobals; standard
# #2F6FED) through the SVG class ColorScheme-ButtonFocus.
ACCENT = "accent"
ACCENT_CLASS = "ColorScheme-ButtonFocus"
STANDARD_ACCENT = "#2F6FED"
BORDER = "#1E2A40"
PANEL_BORDER = "#2A3852"
SUBTLE = "#1A2438"

NONE = "none"


def frame(prefix, y, border, fill, width=1, margin=6, border_opacity=1.0, fill_opacity=1.0, gaps=(0, 0)):
    """One square 9-piece frame (100×100) at row y, plus its margin hints. gaps = pixel rows
    (above, below) the frame, in the panel's frame colour."""
    p = f"{prefix}-" if prefix else ""
    b, size = width, 100
    inner = size - 2 * b
    def paint(color, opacity):
        o = f";fill-opacity:{opacity}" if opacity != 1.0 else ""
        if color == ACCENT:
            return f' class="{ACCENT_CLASS}" style="fill:currentColor{o}"'
        return f' fill="{color}"' + (f' fill-opacity="{opacity}"' if opacity != 1.0 else "")
    out = [f"  <!-- {prefix or 'frame'} -->"]
    pieces = {
        "topleft": (0, 0, b, b), "top": (b, 0, inner, b), "topright": (size - b, 0, b, b),
        "left": (0, b, b, inner), "right": (size - b, b, b, inner),
        "bottomleft": (0, size - b, b, b), "bottom": (b, size - b, inner, b),
        "bottomright": (size - b, size - b, b, b),
    }
    for name, (x, yy, w, h) in pieces.items():
        rect = f'<rect x="{x}" y="{y + yy}" width="{w}" height="{h}"{paint(border, border_opacity)}/>'
        gap = gaps[0] if name.startswith("top") else gaps[1] if name.startswith("bottom") else 0
        if gap:
            # The gap is painted in the panel's frame colour, so the panel's line runs on
            # under the button (QtSvg leaves a see-through rect out of the piece's size)
            gy = y + yy - gap if name.startswith("top") else y + yy + h
            out.append(f'  <g id="{p}{name}">{rect}<rect x="{x}" y="{gy}" width="{w}" height="{gap}" fill="{PANEL_BORDER}"/></g>')
        else:
            out.append(f'  <rect id="{p}{name}"' + rect[5:])
    out.append(f'  <rect id="{p}center" x="{b}" y="{y + b}" width="{inner}" height="{inner}"{paint(fill, fill_opacity)}/>')
    # Inner padding
    out.append(f'  <rect id="{p}hint-top-margin" x="110" y="{y}" width="1" height="{margin}" fill="none"/>')
    out.append(f'  <rect id="{p}hint-bottom-margin" x="115" y="{y}" width="1" height="{margin}" fill="none"/>')
    out.append(f'  <rect id="{p}hint-left-margin" x="110" y="{y + 20}" width="{margin}" height="1" fill="none"/>')
    out.append(f'  <rect id="{p}hint-right-margin" x="110" y="{y + 30}" width="{margin}" height="1" fill="none"/>')
    return out


def write(name, comment, frames, extra=()):
    rows = len(frames)
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="140" height="{rows * 110}" viewBox="0 0 140 {rows * 110}">',
        f"  <!-- {comment}",
        "       Generated by tools/plasma-frames.py – edit that, not this file. -->",
        *extra,
    ]
    if any(ACCENT in args for args in frames):
        lines.append(f'  <defs><style type="text/css" id="current-color-scheme">'
                     f'.{ACCENT_CLASS} {{ color:{STANDARD_ACCENT}; }}</style></defs>')
    for i, args in enumerate(frames):
        lines += frame(*args[:1], i * 110, *args[1:])
    lines.append("</svg>")
    path = THEME / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path)


# Text fields (search in AppGrid, KRunner, network passwords …): dark, thin frame,
# blue frame on focus. Hover/focus are drawn on top of the base.
write(
    "widgets/lineedit.svg",
    "Square GOBLINCAKES text field: dark with a thin frame, blue when focused.",
    [
        ("base", BORDER, NIGHT, 1, 6),
        ("hover", PANEL_BORDER, NONE, 1, 0),
        ("focus", ACCENT, NONE, 1, 0),
        ("focusframe", ACCENT, NONE, 1, 1),
    ],
    extra=['  <rect id="hint-focus-over-base" x="130" y="0" width="1" height="1" fill="none"/>'],
)

# Buttons. "toolbutton-*" are the flat buttons (only visible on hover/press).
write(
    "widgets/button.svg",
    "Square, flat GOBLINCAKES buttons.",
    [
        ("normal", BORDER, DEEP, 1, 6),
        ("hover", ACCENT, NONE, 1, 6),
        ("pressed", ACCENT, ACCENT, 1, 6),
        ("focus", ACCENT, NONE, 1, 6),
        ("toolbutton-hover", PANEL_BORDER, SUBTLE, 1, 6),
        ("toolbutton-pressed", ACCENT, ACCENT, 1, 6),
        ("toolbutton-focus", ACCENT, NONE, 1, 6),
    ],
)

# Highlights in lists and grids (search results, menus, AppGrid).
write(
    "widgets/viewitem.svg",
    "Square GOBLINCAKES highlights: accent blue, see-through.",
    [
        ("normal", ACCENT, NONE, 1, 4, 0.0),
        ("hover", ACCENT, ACCENT, 1, 4, 0.6, 0.18),
        ("selected", ACCENT, ACCENT, 1, 4, 0.9, 0.35),
        ("selected+hover", ACCENT, ACCENT, 1, 4, 1.0, 0.45),
    ],
)

# Task manager (open programs in the dock and the top bar): square, flat. The active
# program a darker shade of the accent (the user found Breeze's accent too bright): the
# accent at 45 % over the panel (#0B1018) – #1B3A78 with the standard blue –, other
# running programs a dim tile, minimised ones only a frame.
TASK_ACTIVE_OPACITY = 0.45
TASK_ATTENTION = "#D9822B"
TASKS = [
    ("normal", SUBTLE, SUBTLE, 1, 2),
    ("hover", PANEL_BORDER, PANEL_BORDER, 1, 2),
    ("focus", ACCENT, ACCENT, 1, 2, 1.0, TASK_ACTIVE_OPACITY),
    ("minimized", SUBTLE, NONE, 1, 2),
    ("attention", TASK_ATTENTION, TASK_ATTENTION, 1, 2, 1.0, 0.35),
]
write(
    "widgets/tasks.svg",
    "Square GOBLINCAKES task buttons: active = dark blue, running = dim tile.",
    # The task buttons fill the panel's whole height and would cover its 1 px frame line, so
    # they stop 1 px short of it. Plasma asks for "north-<state>" first in the top bar (line at
    # the bottom) and "south-<state>" in the dock (floating: line above and below).
    TASKS + [
        (edge + name, *rest, *[1.0] * (6 - len(rest)), gaps)
        for edge, gaps in (("north-", (0, 1)), ("south-", (1, 1)))
        for name, *rest in TASKS
    ],
)

# Tooltips: same as popups, no shadow.
write(
    "widgets/tooltip.svg",
    "Square GOBLINCAKES tooltip, same look as popups (dialogs/background.svg).",
    [("", BORDER, NIGHT, 1, 6)],
)
